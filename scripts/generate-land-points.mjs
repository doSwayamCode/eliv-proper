// Samples Natural Earth 110m land (world-atlas) on an equal-area lat/lon grid and
// writes lib/globe/land-points.ts: int16 pairs (lon*100, lat*100), base64-encoded.
// Run: node scripts/generate-land-points.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { feature } from "topojson-client";

const STEP = 1.1; // degrees between dots
const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
const polygons = land.features.flatMap((f) =>
  f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates,
);

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const isLand = (lon, lat) =>
  polygons.some((p) => inRing(lon, lat, p[0]) && !p.slice(1).some((hole) => inRing(lon, lat, hole)));

const values = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  for (let i = 0; i < n; i++) {
    const lon = -180 + ((i + 0.5) * 360) / n;
    if (isLand(lon, lat)) values.push(Math.round(lon * 100), Math.round(lat * 100));
  }
}
const b64 = Buffer.from(new Int16Array(values).buffer).toString("base64");
mkdirSync("lib/globe", { recursive: true });
writeFileSync(
  "lib/globe/land-points.ts",
  `// Generated by scripts/generate-land-points.mjs from Natural Earth 110m land (world-atlas).\n` +
    `// int16 pairs [lon*100, lat*100], little-endian, base64.\n` +
    `export const LAND_POINTS_B64 =\n  "${b64}";\n`,
);
console.log(`${values.length / 2} land dots`);
